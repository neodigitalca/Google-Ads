#!/usr/bin/env node
/**
 * Import Neo master credentials CSV into repo-root .env.local (gitignored).
 *
 * Usage:
 *   node scripts/sync-neo-master-env.mjs "C:\Users\...\Neo Passwords - Sheet1.csv"
 *
 * Does not print secret values. Preserves unrelated keys already in .env.local.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const ENV_LOCAL = path.join(REPO_ROOT, ".env.local");

const MASTER_PREFIX = "NEO_MASTER_";

/** @type {Record<string, { username?: string; password?: string; website?: string; tfa?: string; ftp?: string }>} */
