function slugKey(company) {
  const k = company.trim().toLowerCase();
  if (SLUG_MAP[k]) return SLUG_MAP[k];
  return company
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
}

function parseCsvLine(line) {
  const out = [];
  let cur = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      inQuotes = !inQuotes;
      continue;
    }
    if (ch === "," && !inQuotes) {
      out.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  out.push(cur);
  return out.map((c) => c.trim());
}

function parseEnvFile(text) {
  /** @type {Map<string, string>} */
  const map = new Map();
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq <= 0) continue;
    map.set(t.slice(0, eq).trim(), t.slice(eq + 1));
  }
  return map;
}

function serializeEnv(map, headerLines) {
  const lines = [...headerLines, ""];
  const keys = [...map.keys()].sort((a, b) => a.localeCompare(b));
  for (const key of keys) {
    const val = map.get(key) ?? "";
    const escaped =
      /[\s#"'\\]/.test(val) || val.includes(",")
        ? `"${val.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`
        : val;
    lines.push(`${key}=${escaped}`);
  }
  lines.push("");
  return lines.join("\n");
}

function main() {
  const csvPath = process.argv[2];
  if (!csvPath || !fs.existsSync(csvPath)) {
    console.error("Usage: node scripts/sync-neo-master-env.mjs <path-to-Neo-Passwords.csv>");
    process.exit(1);
  }

  const raw = fs.readFileSync(csvPath, "utf8");
  const rows = raw.split(/\r?\n/).slice(1);
  /** @type {Map<string, string>} */
  const env = fs.existsSync(ENV_LOCAL)
    ? parseEnvFile(fs.readFileSync(ENV_LOCAL, "utf8"))
    : new Map();

  let imported = 0;
  for (const line of rows) {
    if (!line.trim()) continue;
    const [company, website, username, password, tfa, ftp] = parseCsvLine(line);
    if (!company?.trim()) continue;
    if (!username?.trim() && !password?.trim()) continue;
    const slug = slugKey(company);
    if (!slug) continue;
    const base = `${MASTER_PREFIX}${slug}`;
    if (website?.trim()) env.set(`${base}_WEBSITE`, website.trim());
    if (username?.trim()) env.set(`${base}_USERNAME`, username.trim());
    if (password?.trim()) env.set(`${base}_PASSWORD`, password.trim());
    if (tfa?.trim() && tfa !== "-") env.set(`${base}_TFA`, tfa.trim());
    if (ftp?.trim()) env.set(`${base}_FTP`, ftp.trim());
    imported++;
  }

  env.set("NEO_GITHUB_USERNAME", env.get("NEO_MASTER_GITHUB_USERNAME") ?? "");
  env.set("NEO_GITHUB_PASSWORD", env.get("NEO_MASTER_GITHUB_PASSWORD") ?? "");
  for (const key of ["GH_TOKEN", "GITHUB_TOKEN", "NEO_GITHUB_PAT", "REFACTOR_AUDIT_GH_TOKEN"]) {
    if (!env.has(key)) env.set(key, "");
  }

  const header = [
    "# Neo Digital master credentials (gitignored). Generated by scripts/sync-neo-master-env.mjs",
    `# Source CSV: ${path.basename(csvPath)}`,
    "# Git push/CLI: set GH_TOKEN to a GitHub PAT (account password does not work for git).",
    "# Aliases: NEO_GITHUB_USERNAME / NEO_GITHUB_PASSWORD mirror NEO_MASTER_GITHUB_*.",
  ];

  fs.writeFileSync(ENV_LOCAL, serializeEnv(env, header), "utf8");
  console.log(`[sync-neo-master-env] wrote ${ENV_LOCAL} (${imported} services, ${env.size} keys)`);
}

main();
