#!/usr/bin/env node
/**
 * Sync Neo Pulse refactor audit artifacts to github.com/neodigitalca/refactor-audit
 *
 * Usage (from repo root):
 *   node scripts/backup-refactor-audit.mjs
 *   node scripts/backup-refactor-audit.mjs --skip-push
 *   node scripts/backup-refactor-audit.mjs --backup-dir "D:\backups\refactor-audit"
 *
 * Env (from .env.local / .env):
 *   REFACTOR_AUDIT_BACKUP_DIR  Local clone path (default: <repo>/refactor-audit-git)
 *   REFACTOR_AUDIT_REMOTE      Git remote URL
 *   GH_TOKEN / GITHUB_TOKEN / NEO_GITHUB_PAT / REFACTOR_AUDIT_GH_TOKEN  GitHub PAT for push
 *   NEO_GITHUB_USERNAME         GitHub login (default: NEO_MASTER_GITHUB_USERNAME)
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import {
  loadRepoEnv,
  githubPushToken,
  githubAuthUsername,
  withGitHubTokenRemote,
} from "./load-repo-env.mjs";

loadRepoEnv();

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const DEFAULT_REMOTE = "https://github.com/neodigitalca/refactor-audit.git";
const DEFAULT_BACKUP_DIR = path.join(REPO_ROOT, "refactor-audit-git");

const args = process.argv.slice(2);
const skipPush = args.includes("--skip-push");
const backupDirArg = args.find((a) => !a.startsWith("--"));
const BACKUP_DIR = path.resolve(
  backupDirArg || process.env.REFACTOR_AUDIT_BACKUP_DIR || DEFAULT_BACKUP_DIR,
);
const REMOTE = process.env.REFACTOR_AUDIT_REMOTE || DEFAULT_REMOTE;

function runGit(cwd, gitArgs, { allowFail = false, env = process.env } = {}) {
  const r = spawnSync("git", gitArgs, { cwd, encoding: "utf8", env });
  if (r.status !== 0 && !allowFail) {
    const msg = (r.stderr || r.stdout || "").trim() || `git ${gitArgs.join(" ")} failed`;
    throw new Error(msg);
  }
  return (r.stdout || "").trim();
}

function pushOriginMain(cwd) {
  const token = githubPushToken();
  if (!token) {
    runGit(cwd, ["push", "-u", "origin", "main"]);
    return;
  }
  const authRemote = withGitHubTokenRemote(REMOTE, token, githubAuthUsername());
  runGit(cwd, ["remote", "set-url", "origin", authRemote]);
  try {
    runGit(cwd, ["push", "-u", "origin", "main"]);
  } finally {
    runGit(cwd, ["remote", "set-url", "origin", REMOTE], { allowFail: true });
  }
}

function copyFile(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function copyIfExists(srcRel, destRel) {
  const src = path.join(REPO_ROOT, srcRel);
  if (!fs.existsSync(src)) {
    console.warn(`[backup-refactor-audit] skip missing: ${srcRel}`);
    return false;
  }
  copyFile(src, path.join(BACKUP_DIR, destRel));
  console.log(`[backup-refactor-audit] copied ${srcRel} -> ${destRel}`);
  return true;
}

function ensureClone() {
  if (fs.existsSync(path.join(BACKUP_DIR, ".git"))) {
    runGit(BACKUP_DIR, ["fetch", "origin"]);
    runGit(BACKUP_DIR, ["checkout", "main"], { allowFail: true });
    runGit(BACKUP_DIR, ["pull", "--ff-only", "origin", "main"], { allowFail: true });
    return;
  }
  fs.mkdirSync(path.dirname(BACKUP_DIR), { recursive: true });
  console.log(`[backup-refactor-audit] cloning ${REMOTE} -> ${BACKUP_DIR}`);
  runGit(path.dirname(BACKUP_DIR), [
    "clone",
    REMOTE,
    path.basename(BACKUP_DIR),
  ]);
}

function writeReadmeIfMissing() {
  const readmePath = path.join(BACKUP_DIR, "README.md");
  if (fs.existsSync(readmePath)) return;
  const text = `# refactor-audit

Backup mirror for Neo Pulse monolith refactor planning artifacts.

Generated by \`scripts/backup-refactor-audit.mjs\` from the main Neo Pulse repo (\`neodigitalca/Google-Ads\`).

## Contents

- \`audits/\` — monolith inventory notes and JSON
- \`scripts/generate-monolith-inventory.mjs\` — regenerates inventory in the source repo
- \`backup-manifest.json\` — source commit and sync timestamp
- \`refactor-git-log.txt\` — recent commits from source at sync time
`;
  fs.writeFileSync(readmePath, text, "utf8");
  console.log("[backup-refactor-audit] wrote README.md");
}

function syncArtifacts() {
  copyIfExists("docs/audits/monolith-audit-notes.md", "audits/monolith-audit-notes.md");
  copyIfExists("docs/audits/monolith-inventory.json", "audits/monolith-inventory.json");
  copyIfExists("scripts/generate-monolith-inventory.mjs", "scripts/generate-monolith-inventory.mjs");

  const plansSrc = path.join(REPO_ROOT, ".cursor", "plans");
  const plansDest = path.join(BACKUP_DIR, "cursor-plans");
  if (fs.existsSync(plansSrc)) {
    fs.mkdirSync(plansDest, { recursive: true });
    for (const name of fs.readdirSync(plansSrc)) {
      if (!name.endsWith(".md")) continue;
      copyFile(path.join(plansSrc, name), path.join(plansDest, name));
    }
    console.log("[backup-refactor-audit] synced .cursor/plans/*.md -> cursor-plans/");
  }

  const sourceHead = runGit(REPO_ROOT, ["rev-parse", "HEAD"]);
  const sourceBranch = runGit(REPO_ROOT, ["rev-parse", "--abbrev-ref", "HEAD"]);
  let logTail = "";
  try {
    logTail = runGit(REPO_ROOT, ["log", "-50", "--oneline"]);
  } catch {
    logTail = "";
  }

  const manifest = {
    syncedAt: new Date().toISOString(),
    sourceRemote: "https://github.com/neodigitalca/Google-Ads.git",
    backupRemote: REMOTE,
    sourceRoot: REPO_ROOT,
    sourceBranch,
    sourceCommit: sourceHead,
  };
  fs.writeFileSync(
    path.join(BACKUP_DIR, "backup-manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );
  fs.writeFileSync(
    path.join(BACKUP_DIR, "refactor-git-log.txt"),
    logTail ? `${logTail}\n` : "",
    "utf8",
  );
}

function commitAndPush() {
  runGit(BACKUP_DIR, ["add", "-A"]);
  const status = runGit(BACKUP_DIR, ["status", "--porcelain"]);
  if (!status) {
    console.log("[backup-refactor-audit] backup clone already up to date; nothing to commit");
    if (!skipPush) {
      pushOriginMain(BACKUP_DIR);
    }
    return;
  }
  const head = runGit(REPO_ROOT, ["rev-parse", "--short", "HEAD"]);
  runGit(BACKUP_DIR, ["commit", "-m", `Sync refactor audit from Neo Pulse @ ${head}`]);
  if (skipPush) {
    console.log("[backup-refactor-audit] committed locally (--skip-push)");
    return;
  }
  pushOriginMain(BACKUP_DIR);
  console.log("[backup-refactor-audit] pushed to origin/main");
}

function main() {
  console.log(`[backup-refactor-audit] source: ${REPO_ROOT}`);
  console.log(`[backup-refactor-audit] backup clone: ${BACKUP_DIR}`);
  ensureClone();
  writeReadmeIfMissing();
  syncArtifacts();
  commitAndPush();
  console.log("[backup-refactor-audit] done");
}

try {
  main();
} catch (err) {
  console.error("[backup-refactor-audit] failed:", err instanceof Error ? err.message : err);
  process.exit(1);
}
