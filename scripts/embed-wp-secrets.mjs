#!/usr/bin/env node
/**
 * Writes wordpress-plugins/neo-pulse-wp/.env from repo root .env before deploy.
 *
 * Usage:
 *   node scripts/embed-wp-secrets.mjs
 *   npm run embed:neo-pulse-wp-secrets
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'wordpress-plugins', 'neo-pulse-wp', '.env');

function loadDotEnv(filePath) {
  /** @type {Record<string, string>} */
  const out = {};
  if (!fs.existsSync(filePath)) return out;
  for (const line of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = t.indexOf('=');
    if (eq < 1) continue;
    const k = t.slice(0, eq).trim();
    let v = t.slice(eq + 1).trim();
    if (
      (v.startsWith('"') && v.endsWith('"')) ||
      (v.startsWith("'") && v.endsWith("'"))
    ) {
      v = v.slice(1, -1);
    }
    out[k] = v;
  }
  return out;
}

function pick(env, ...keys) {
  for (const key of keys) {
    const val = env[key];
    if (typeof val === 'string' && val.trim() !== '') {
      return val.trim();
    }
  }
  return '';
}

function main() {
  const dotenv = loadDotEnv(path.join(ROOT, '.env'));

  const lines = [
    '# Generated by scripts/embed-wp-secrets.mjs — do not commit',
    '',
    `NEO_PULSE_WP_OPENROUTER_API_KEY=${pick(dotenv, 'NEO_PULSE_WP_OPENROUTER_API_KEY', 'OPEN_ROUTER_API_KEY', 'OPENROUTER_API_KEY')}`,
    '',
    `NEO_PULSE_WP_DATAFORSEO_LOGIN=${pick(dotenv, 'NEO_PULSE_WP_DATAFORSEO_LOGIN', 'DATAFORSEO_API_LOGIN', 'DATAFORSEO_LOGIN')}`,
    `NEO_PULSE_WP_DATAFORSEO_PASSWORD=${pick(dotenv, 'NEO_PULSE_WP_DATAFORSEO_PASSWORD', 'DATAFORSEO_API_PASSWORD', 'DATAFORSEO_PASSWORD')}`,
    '',
    `NEO_PULSE_WP_AGENTMAIL_API_KEY=${pick(dotenv, 'NEO_PULSE_WP_AGENTMAIL_API_KEY', 'AGENTMAIL_API_KEY')}`,
    `NEO_PULSE_WP_AGENTMAIL_INBOX=${pick(dotenv, 'NEO_PULSE_WP_AGENTMAIL_INBOX', 'AGENTMAIL_INBOX', 'AGENTMAIL_GENERAL_EMAIL')}`,
    '',
    `NEO_PULSE_WP_SEMRUSH_API_KEY=${pick(dotenv, 'NEO_PULSE_WP_SEMRUSH_API_KEY', 'SEMRUSH_API_KEY')}`,
    '',
    `NEO_PULSE_WP_CHEKKIT_WEBHOOK_URL=${pick(dotenv, 'NEO_PULSE_WP_CHEKKIT_WEBHOOK_URL', 'CHEKKIT_WEBHOOK_URL', 'CHEKKIT_EVENTS_WEBHOOK_URL')}`,
    '',
  ];

  fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
  console.log('Wrote', OUT);
}

main();
